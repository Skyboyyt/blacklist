/**
 * Neutral movement wording. Direction is a blockchain fact about the movement, not
 * about who initiated it. An unvalidated log is reported as a log claim, not as proof
 * that funds moved (chain-data §2).
 */
export function transferMovementLabel(
  direction: 'in' | 'out',
  evidenceLevel: keyof typeof EVIDENCE_LEVEL_COPY,
): string {
  const movement = direction === 'in' ? 'incoming transfer of' : 'outgoing transfer of';
  if (evidenceLevel === 'observed_log') return `A log reports an ${movement}`;
  return direction === 'in' ? 'Incoming transfer of' : 'Outgoing transfer of';
}


// Builds an atomic Neon SQL-Editor apply script from committed migrations (owner runbooks).
// It embeds each file verbatim, grants the runtime role exactly what the repository runner
// would (read/write on new tables; SELECT/INSERT on tables guarded by reject_mutation), and
// inserts the ledger rows with each file's SHA-256. Nothing is executed.
// Usage: node scripts/build-neon-apply.mjs <expected-ledger-count> <out.sql> <migration> [...]
//   migrations are paths relative to packages/db/migrations, in apply order.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { basename } from 'node:path';

const [expected, out, ...files] = process.argv.slice(2);
if (!/^\d+$/u.test(expected ?? '') || !out || files.length === 0) {
  console.error(
    'Usage: node scripts/build-neon-apply.mjs <expected-ledger-count> <out.sql> <migration> [...]',
  );
  process.exit(1);
}
const sources = files.map((file) => {
  const text = readFileSync(new URL(`../packages/db/migrations/${file}`, import.meta.url), 'utf8');
  return { file, name: basename(file), text, sha256: createHash('sha256').update(text).digest('hex') };
});
const all = sources.map((s) => s.text).join('\n');
const created = [...all.matchAll(/CREATE TABLE "blacklist"\."([a-z_]+)"/gu)].map((m) => m[1]);
const appendOnly = new Set(
  [
    ...all.matchAll(/ON blacklist\.([a-z_]+) FOR EACH ROW EXECUTE FUNCTION blacklist\.reject_mutation\(\)/gu),
  ].map((m) => m[1]),
);
const readWrite = created.filter((t) => !appendOnly.has(t));
const insertOnly = created.filter((t) => appendOnly.has(t));
const names = sources.map((s) => `'${s.name}'`).join(', ');
const lines = [
  `-- Blacklist staging (Neon): apply ONLY ${sources.map((s) => s.file).join(' and ')} as`,
  '-- blacklist_migrator, atomically with runtime grants and ledger rows. Any error rolls back',
  '-- everything. Generated by scripts/build-neon-apply.mjs; do not edit by hand.',
  'BEGIN;',
  "SET LOCAL lock_timeout = '5s';",
  "SET LOCAL statement_timeout = '120s';",
  'DO $role$ BEGIN',
  "  IF current_user <> 'blacklist_migrator' AND NOT pg_has_role('blacklist_migrator', 'SET') THEN",
  "    EXECUTE 'GRANT blacklist_migrator TO ' || quote_ident(current_user) || ' WITH INHERIT FALSE, SET TRUE';",
  "    PERFORM set_config('blacklist.temporary_set_grant', current_user, true);",
  '  END IF;',
  'END $role$;',
  'SET LOCAL ROLE blacklist_migrator;',
  'DO $guard$ BEGIN',
  `  IF EXISTS (SELECT 1 FROM blacklist_migrations.applied WHERE name IN (${names})) THEN`,
  "    RAISE EXCEPTION 'already applied; nothing changed';",
  '  END IF;',
  `  IF (SELECT count(*) FROM blacklist_migrations.applied) <> ${expected} THEN`,
  `    RAISE EXCEPTION 'ledger is not at the expected ${expected} entries; nothing changed';`,
  '  END IF;',
  'END $guard$;',
  ...sources.flatMap((s) => [
    `-- ---- begin ${s.file} (verbatim) ----`,
    s.text.trimEnd(),
    `-- ---- end ${s.file} ----`,
  ]),
  ...(readWrite.length
    ? [
        `GRANT SELECT, INSERT, UPDATE, DELETE ON ${readWrite.map((t) => `blacklist.${t}`).join(', ')} TO blacklist_app;`,
      ]
    : []),
  ...(insertOnly.length
    ? [`GRANT SELECT, INSERT ON ${insertOnly.map((t) => `blacklist.${t}`).join(', ')} TO blacklist_app;`]
    : []),
  'INSERT INTO blacklist_migrations.applied(name, sha256) VALUES',
  sources.map((s) => `  ('${s.name}', '${s.sha256}')`).join(',\n') + ';',
  'RESET ROLE;',
  "DO $role$ DECLARE granted text := current_setting('blacklist.temporary_set_grant', true); BEGIN",
  "  IF coalesce(granted, '') <> '' THEN",
  "    EXECUTE 'REVOKE blacklist_migrator FROM ' || quote_ident(granted);",
  '  END IF;',
  'END $role$;',
  'COMMIT;',
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(
  `${out}: ${sources.length} files, ${created.length} new tables (${insertOnly.length} append-only)`,
);
